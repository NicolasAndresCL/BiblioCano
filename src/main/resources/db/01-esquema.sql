-- =====================================================================================
-- BiblioCano: esquema de la base de datos (PostgreSQL 17)
--
-- Es la traducción directa del modelo de datos (docs/diagramas/fuentes/2-modelo-de-datos.puml):
-- mismas cinco tablas, claves y relaciones. Lo corre PostgreSQL al crear el volumen
-- (docker-entrypoint-initdb.d) y la aplicación con `reiniciar-datos`.
--
-- ATENCIÓN: empieza borrando las tablas. Solo contiene datos de ejemplo.
-- =====================================================================================

DROP TABLE IF EXISTS prestamo, ejemplar, libro, socio, bibliotecario CASCADE;

CREATE TABLE bibliotecario (
    id_bibliotecario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    usuario          VARCHAR(50)  NOT NULL UNIQUE,
    -- hash PBKDF2 «iteraciones:sal:hash», nunca la contraseña en claro
    password_hash    VARCHAR(255) NOT NULL
);

CREATE TABLE socio (
    id_socio    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut         VARCHAR(12)  NOT NULL UNIQUE,
    nombre      VARCHAR(100) NOT NULL,
    correo      VARCHAR(100) NOT NULL,
    tiene_multa BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE libro (
    isbn      VARCHAR(20)  PRIMARY KEY,
    titulo    VARCHAR(150) NOT NULL,
    autor     VARCHAR(100) NOT NULL,
    categoria VARCHAR(50)  NOT NULL
);

-- Composición Libro ◆── Ejemplar: la copia no existe sin su título (ON DELETE CASCADE)
CREATE TABLE ejemplar (
    codigo_barra VARCHAR(30) PRIMARY KEY,
    isbn         VARCHAR(20) NOT NULL REFERENCES libro (isbn) ON DELETE CASCADE,
    ubicacion    VARCHAR(50) NOT NULL,
    estado       VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE'
                 CHECK (estado IN ('DISPONIBLE', 'PRESTADO', 'MANTENIMIENTO'))
);

CREATE TABLE prestamo (
    id_prestamo               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bibliotecario          INT         NOT NULL REFERENCES bibliotecario (id_bibliotecario),
    id_socio                  INT         NOT NULL REFERENCES socio (id_socio),
    codigo_barra              VARCHAR(30) NOT NULL REFERENCES ejemplar (codigo_barra),
    fecha_prestamo            DATE        NOT NULL,
    fecha_devolucion_esperada DATE        NOT NULL,
    fecha_devolucion_real     DATE,
    estado                    VARCHAR(20) NOT NULL CHECK (estado IN ('ACTIVO', 'DEVUELTO')),
    -- pesos chilenos enteros: el peso no usa decimales
    multa                     INTEGER     NOT NULL DEFAULT 0 CHECK (multa >= 0),
    CHECK (fecha_devolucion_esperada > fecha_prestamo),
    -- un préstamo activo no tiene fecha real; uno devuelto sí
    CHECK ((estado = 'ACTIVO' AND fecha_devolucion_real IS NULL)
        OR (estado = 'DEVUELTO' AND fecha_devolucion_real IS NOT NULL))
);

-- Regla de negocio protegida por la base: un ejemplar tiene a lo más UN préstamo activo.
-- Si dos bibliotecarios prestan la misma copia al mismo tiempo, el segundo INSERT falla.
CREATE UNIQUE INDEX uq_prestamo_activo_por_ejemplar ON prestamo (codigo_barra) WHERE estado = 'ACTIVO';

CREATE INDEX ix_prestamo_socio ON prestamo (id_socio);
